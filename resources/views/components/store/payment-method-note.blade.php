    @if ($gatewayEnabled && $manualAvailable)
        @if ($stage === 'after-order')
            برای این سفارش می‌توانید پرداخت آنلاین با زرین‌پال را انجام دهید یا به‌جای آن کارت‌به‌کارت کنید و تصویر رسید را بفرستید.
        @else
            پس از ثبت سفارش، پرداخت آنلاین با زرین‌پال و روش کارت‌به‌کارت با ارسال رسید در دسترس خواهد بود؛ می‌توانید یکی از این دو روش را انتخاب کنید. سفارش پس از تأیید پرداخت وارد مرحله آماده‌سازی می‌شود.
        @endif
    @elseif ($gatewayEnabled)
        پرداخت آنلاین با زرین‌پال برای این سفارش در دسترس است.
    @elseif ($manualAvailable)
        @if ($stage === 'after-order')
            روش پرداخت این سفارش از طریق کارت‌به‌کارت و ارسال رسید است. پس از انتقال مبلغ دقیق، تصویر رسید را ارسال کنید؛ تأیید سفارش بعد از بررسی واریز بانکی انجام می‌شود.
        @else
            پرداخت در حال حاضر از طریق کارت‌به‌کارت و ارسال رسید انجام می‌شود. مبلغ دقیق و اطلاعات کارت پس از ثبت سفارش نمایش داده می‌شود؛ سفارش پس از بررسی و تأیید واریز بانکی وارد مرحله آماده‌سازی می‌شود.
        @endif
    @else
        اطلاعات پرداخت برای این سفارش در دسترس نیست؛ برای راهنمایی با پشتیبانی فروشگاه تماس بگیرید.
    @endif
</p>
